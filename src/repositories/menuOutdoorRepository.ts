import { supabase } from '../lib/supabase';
import { BackendError, requireBackend, toBackendError } from '../lib/backend';
import type { PublishedMedia } from './mediaRepository';

/** Only presentation fields from the public RPC; no account/customer information. */
export interface PublicMenuOutdoorSlide {
  id: string;
  imageUrl?: string;
  videoUrl?: string;
  title?: string;
  productId?: string;
}

export interface MenuOutdoorSlide extends PublicMenuOutdoorSlide {
  tenantId: string;
  assetId: string;
  sortOrder: number;
  active: boolean;
  startsAt: string | null;
  endsAt: string | null;
  /** Unpublished media stays manageable without disclosing a private storage path. */
  mediaAvailable: boolean;
}

export interface MenuOutdoorSlideDraft {
  id?: string;
  assetId: string;
  title?: string;
  productId?: string;
  sortOrder: number;
  active: boolean;
  startsAt?: string | null;
  endsAt?: string | null;
}

// Paths are generated by the governed marketing publication flow, never entered URLs.
const UUID_PATH = '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}';
const PUBLISHED_PATH = new RegExp(`^${UUID_PATH}/published/${UUID_PATH}\\.(?:jpg|jpeg|png|webp|mp4|webm)$`, 'i');

function publicSlide(row: Record<string, unknown>): PublicMenuOutdoorSlide {
  if (typeof row.id !== 'string' || typeof row.public_path !== 'string' || !PUBLISHED_PATH.test(row.public_path)
    || (row.media_type !== 'IMAGE' && row.media_type !== 'VIDEO')) {
    throw new BackendError('MENU_OUTDOOR_INVALID', 'A mídia do outdoor não é válida.');
  }
  const url = supabase.storage.from('marketing-public').getPublicUrl(row.public_path).data.publicUrl;
  return {
    id: row.id,
    ...(row.media_type === 'VIDEO' ? { videoUrl: url } : { imageUrl: url }),
    ...(typeof row.title === 'string' && row.title ? { title: row.title } : {}),
    ...(typeof row.product_id === 'string' && row.product_id ? { productId: row.product_id } : {}),
  };
}

function staffSlide(row: Record<string, unknown>): MenuOutdoorSlide {
  return {
    ...(row.public_path == null ? {
      id: String(row.id),
      ...(typeof row.title === 'string' && row.title ? { title: row.title } : {}),
      ...(typeof row.product_id === 'string' && row.product_id ? { productId: row.product_id } : {}),
    } : publicSlide(row)),
    mediaAvailable: typeof row.public_path === 'string',
    tenantId: String(row.tenant_id),
    assetId: String(row.asset_id),
    sortOrder: Number(row.sort_order),
    active: row.active === true,
    startsAt: typeof row.starts_at === 'string' ? row.starts_at : null,
    endsAt: typeof row.ends_at === 'string' ? row.ends_at : null,
  };
}

export const menuOutdoorRepository = {
  async getPublicSlides(slug: string): Promise<PublicMenuOutdoorSlide[]> {
    requireBackend('outdoor do cardápio');
    const { data, error } = await supabase.rpc('list_public_menu_outdoor', { p_slug: slug });
    if (error) throw toBackendError(error, 'Não foi possível carregar o outdoor do cardápio.');
    return (Array.isArray(data) ? data : []).map(publicSlide);
  },

  async list(tenantId: string): Promise<MenuOutdoorSlide[]> {
    requireBackend('outdoor do cardápio');
    const { data, error } = await supabase.rpc('list_menu_outdoor_slides', { p_tenant_id: tenantId });
    if (error) throw toBackendError(error, 'Não foi possível carregar os banners.');
    return (Array.isArray(data) ? data : []).map(staffSlide);
  },

  /** Existing marketing RLS restricts this library to active owners/managers of this tenant. */
  async listPublishedMedia(tenantId: string): Promise<PublishedMedia[]> {
    requireBackend('mídia de marketing');
    const { data, error } = await supabase.from('marketing_media_assets')
      .select('id,tenant_id,media_type,public_path')
      .eq('tenant_id', tenantId).eq('kind', 'CREATIVE').eq('status', 'PUBLISHED')
      .order('created_at', { ascending: false }).limit(100);
    if (error) throw toBackendError(error, 'Não foi possível carregar a biblioteca de mídia.');
    return (Array.isArray(data) ? data : []).flatMap(row => {
      if (row.tenant_id !== tenantId || typeof row.public_path !== 'string'
        || !row.public_path.startsWith(`${tenantId}/published/${row.id}.`) || !PUBLISHED_PATH.test(row.public_path)
        || (row.media_type !== 'IMAGE' && row.media_type !== 'VIDEO')) return [];
      const slide = publicSlide(row);
      return [{ assetId: row.id, publicPath: row.public_path,
        publicUrl: slide.imageUrl || slide.videoUrl!, mediaType: row.media_type as 'IMAGE' | 'VIDEO' }];
    });
  },

  /** Server validates membership, tenant-owned product and published asset on every write. */
  async save(tenantId: string, draft: MenuOutdoorSlideDraft): Promise<MenuOutdoorSlide> {
    requireBackend('outdoor do cardápio');
    const { data, error } = await supabase.rpc('save_menu_outdoor_slide', {
      p_tenant_id: tenantId,
      p_id: draft.id ?? null,
      p_asset_id: draft.assetId,
      p_title: draft.title?.trim() || null,
      p_product_id: draft.productId || null,
      p_sort_order: draft.sortOrder,
      p_active: draft.active,
      p_starts_at: draft.startsAt || null,
      p_ends_at: draft.endsAt || null,
    });
    if (error) throw toBackendError(error, 'Não foi possível salvar o banner.');
    return staffSlide(data);
  },
};
